// ── Bundle cache: built ONCE per process, never per request ──────────────────
let _bundleCache: string | null = null;
async function getBundleLocation(): Promise<string> {
  if (_bundleCache) return _bundleCache;
  console.log("[render-video] Building bundle (one time)...");
  const { bundle } = await import("@remotion/bundler");
  _bundleCache = await bundle({
    entryPoint: path.join(process.cwd(), "remotion", "index.ts"),
    webpackOverride: (c) => c,
  });
  return _bundleCache;
}

// ensures no NaN durations ever reach Remotion
function asFiniteSeconds(v: any, fallback = 6) {
  const n = typeof v === "number" ? v : Number(v);
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

// ── Studio scene shape (from ProjectStudio) ───────────────────────────────────
// Extends the existing storyboard shape with Studio-specific fields.
interface StudioScene {
  // Scene type — controls priority chain
  mode?: "webcam" | "broll" | "ai" | "media_asset";
  // Veo3 prompt (generated by Gemini in generate-scenes)
  aiPrompt?: string;
  // Media pool asset auto-assigned in generate-scenes / add-scene
  mediaAssetUrl?: string | null;
  mediaAssetId?: string | null;
  mediaCategory?: string | null;
  // User uploaded background (broll mode)
  uploadedUrl?: string | null;
  uploadedType?: "video" | "image" | null;
  // Webcam / broll recorded clip (already uploaded to Spaces before render)
  recordedUrl?: string | null;
  // Overlays
  overlays?: Array<{
    id: string;
    type: "video" | "image";
    url?: string | null;
    startSeconds: number;
    endSeconds: number;
    x: number;
    y: number;
    w: number;
    h: number;
    radius?: number;
  }> | null;
}

export async function POST(req: NextRequest) {
  const tempFiles: string[] = [];

  try {
    const body = await req.json();

    const {
      body_text,
      companyName,
      accentColor,
      useVeo3 = false,           // Studio default: don't auto-Veo3 every scene
      voiceId = "EXAVITQu4vr4xnSDxMaL" as VoiceId,  // Sarah — default
      enableVoice = true,          // false = music only, skip TTS entirely
      webcamClips = [],
      preGeneratedScript,
      captionsMode = "off",       // Always off from Studio
    } = body;

    // ── Studio scenes (from ProjectStudio) ───────────────────────────────────
    // These carry mode, mediaAssetUrl, aiPrompt, recordedUrl, uploadedUrl etc.
    const studioScenes: StudioScene[] | null = Array.isArray(body.storyboardScenes)
      ? body.storyboardScenes
      : null;

    // Uploaded scene backgrounds (broll file uploads, already on Spaces)
    const uploadedSceneMediaFromBody: Array<{ index: number; url: string; type: "video" | "image" }> =
      Array.isArray(body.uploadedSceneMedia) ? body.uploadedSceneMedia : [];

    // ── 1) Script ─────────────────────────────────────────────────────────────
    let script: VoiceoverScript;

    if (preGeneratedScript?.segments?.length >= 1) {
      script = preGeneratedScript as VoiceoverScript;
      console.log("[render-video] Using pre-generated script from Studio");
    } else {
      script = await generateVoiceoverScript(body_text || "", companyName, accentColor);
    }

    console.log(
      `[render-video] ${script.segments.length} segs | font="${script.styleDNA?.primaryFont}" tone="${script.styleDNA?.tone}"`
    );

    // ── 2) Campaign data ──────────────────────────────────────────────────────
    const campaignData: CampaignData = {
      hook:        body.hook        || script.segments[0]?.screenText || "",
      subheading:  body.subheading  || script.segments[1]?.screenText || "",
      cta:         body.cta         || script.segments[script.segments.length - 1]?.ctaText || "",
      companyName: script.companyName,
      proof:       body.proof    || "",
      bullets:     body.bullets  || [],
      hashtags:    body.hashtags || "",
      location:    body.location || "",
      ctaLink:     body.ctaLink  || "",
    };

    // ── 3) Webcam / broll clip maps ───────────────────────────────────────────
    const webcamClipMap = new Map<number, { url: string; duration: number }>();
    const brollClipMap  = new Map<number, { url: string; duration: number }>();

    for (const c of webcamClips as any[]) {
      const segIdx = Number(c.segmentIndex);
      if (!Number.isFinite(segIdx)) continue;

      const entry = {
        url:      String(c.url || ""),
        duration: asFiniteSeconds(c.durationSeconds, 0) > 0
          ? asFiniteSeconds(c.durationSeconds, 6)
          : asFiniteSeconds(script.segments[segIdx]?.durationSeconds, 6),
      };
      if (!entry.url) continue;

      if (c.isWebcam) webcamClipMap.set(segIdx, entry);
      else            brollClipMap.set(segIdx, entry);
    }

    const hasAnyUserVoice = (webcamClips as any[]).some((c) => c?.hasAudio === true);
    console.log(
      `[render-video] Voice mode: ${hasAnyUserVoice ? "USER (webcam+broll audio)" : "AI ElevenLabs"}`
    );

    // ── 4) Scene assets — Studio priority chain ───────────────────────────────
    //
    // Priority 1 : Recorded webcam/broll clip (already uploaded, has audio)
    // Priority 2 : User-uploaded broll file (uploadedUrl from broll mode)
    // Priority 3 : Media pool asset (mediaAssetUrl — auto-assigned in generate-scenes)
    // Priority 4 : Veo3 AI generation (mode==="ai" or useVeo3===true)
    // Priority 5 : Pexels video fallback (skip for ai mode)
    // Priority 6 : Unsplash image fallback
    //
    const sceneAssets: { videoUrl: string | null; imageUrl: string | null; source: string }[] = [];

    for (let i = 0; i < script.segments.length; i++) {
      const seg      = script.segments[i];
      const studio   = studioScenes?.[i] ?? null;
      const mode     = studio?.mode ?? "media_asset";
      const aiPrompt = studio?.aiPrompt ?? "";

      let videoUrl: string | null = null;
      let imageUrl: string | null = null;
      let source = "color";

      // ── Priority 1: recorded webcam/broll clip ──────────────────────────
      if (!videoUrl && !imageUrl && studio?.recordedUrl) {
        videoUrl = studio.recordedUrl;
        source   = mode === "webcam" ? "webcam" : "broll-recorded";
        console.log(`[render-video] Scene ${i + 1}: recorded clip (${mode})`);
      }

      // Also check webcamClipMap (clips uploaded just before render call)
      if (!videoUrl && !imageUrl && (mode === "webcam" || mode === "broll")) {
        const wc = webcamClipMap.get(i) ?? brollClipMap.get(i);
        if (wc?.url) {
          videoUrl = wc.url;
          source   = mode === "webcam" ? "webcam" : "broll-recorded";
          console.log(`[render-video] Scene ${i + 1}: clip from webcamClips[] (${mode})`);
        }
      }

      // ── Priority 2: user-uploaded broll file ────────────────────────────
      if (!videoUrl && !imageUrl && studio?.uploadedUrl) {
        const bgType = studio.uploadedType ?? "video";
        if (bgType === "video") { videoUrl = studio.uploadedUrl; }
        else                    { imageUrl = studio.uploadedUrl; }
        source = "upload";
        console.log(`[render-video] Scene ${i + 1}: uploaded ${bgType}`);
      }

      // Also check uploadedSceneMedia (files uploaded just before render)
      if (!videoUrl && !imageUrl) {
        const up = uploadedSceneMediaFromBody.find((u) => u.index === i);
        if (up?.url) {
          if (up.type === "video") { videoUrl = up.url; }
          else                     { imageUrl = up.url; }
          source = "upload";
          console.log(`[render-video] Scene ${i + 1}: uploadedSceneMedia (${up.type})`);
        }
      }

      // ── Priority 3: media pool asset (media_asset mode) ─────────────────
      if (!videoUrl && !imageUrl && studio?.mediaAssetUrl) {
        videoUrl = studio.mediaAssetUrl;
        source   = "media_asset";
        console.log(`[render-video] Scene ${i + 1}: media pool asset`);
      }

      // ── Priority 4: Veo3 (ai mode always; other modes only if useVeo3) ───
      if (!videoUrl && !imageUrl) {
        const shouldVeo = mode === "ai" || useVeo3;
        if (shouldVeo) {
          try {
            const dur = Math.min(8, Math.max(4, asFiniteSeconds(seg.durationSeconds, 6))) as 4|5|6|7|8;
            const veoPrompt = (mode === "ai" && aiPrompt)
              ? `${aiPrompt}. Style: ${script.styleDNA?.cinematicMood || "cinematic"}`
              : `${seg.visualDescription}. Style: ${script.styleDNA?.cinematicMood || "cinematic"}`;

            const r = await generateVeo3Video(veoPrompt, dur, "9:16", script.veo3StyleHint);
            if (r.videoUrl) {
              videoUrl = r.videoUrl;
              source   = mode === "ai" ? "veo3-ai" : "veo3";
              console.log(`[render-video] Scene ${i + 1}: ${source}`);
            }
          } catch (e) {
            console.warn(`[scene ${i + 1}] Veo3 failed:`, e);
          }
        }
      }

      // ── Priority 5: Pexels fallback (skip for ai mode) ──────────────────
      if (!videoUrl && !imageUrl && mode !== "ai") {
        try {
          videoUrl = await fetchBestPexelsVideo([
            seg.pexelsQuery,
            `${script.companyName} ${seg.position}`,
            "business cinematic",
          ]);
          if (videoUrl) {
            source = "pexels";
            console.log(`[render-video] Scene ${i + 1}: pexels`);
          }
        } catch (e) {
          console.warn(`[scene ${i + 1}] Pexels:`, e);
        }
      }

      // ── Priority 6: Unsplash image fallback ─────────────────────────────
      if (!videoUrl && !imageUrl) {
        try {
          imageUrl = await fetchBestUnsplashImage([seg.pexelsQuery, script.companyName], "portrait");
          source   = "image";
          console.log(`[render-video] Scene ${i + 1}: unsplash image`);
        } catch (e) {
          console.warn(`[scene ${i + 1}] Unsplash:`, e);
        }
      }

      if (!videoUrl && !imageUrl) {
        console.log(`[render-video] Scene ${i + 1}: color card fallback`);
      }

      sceneAssets.push({ videoUrl, imageUrl, source });
    }

    // ── 5) Audio first — so real duration drives scene lengths ──────────────
    // Generate ElevenLabs voice BEFORE calculating durations.
    // We write it to a temp file, measure it with ffprobe, then redistribute
    // that real total duration across scenes proportionally.
    // This guarantees the output video is NEVER shorter than the voice track.

    // ── Audio strategy ────────────────────────────────────────────────────────
    //
    // RULE: keep it dead simple.
    //
    // Webcam scene  → video clip already has audio baked in.
    //                 <Video muted=false> plays it. NO extra <Audio> tag.
    //
    // Non-webcam    → needs narration. We generate ONE ElevenLabs track per
    //                 non-webcam scene individually. Each gets its own upload URL.
    //                 Stored in perSceneAiVoice[i] and played as <Audio> inside
    //                 that scene's <Sequence>. Perfectly in sync, zero slicing.
    //
    // This avoids ALL the slice/startFrom complexity that was causing silence.

    let voiceUrl: string | null = null;                           // unused in new logic, kept for compat
    const sceneAudioUrls: (string | null)[] = new Array(script.segments.length).fill(null);
    const brollAudioUrls: (string | null)[] = new Array(script.segments.length).fill(null);
    const sceneSpeechMarkers: SpeechMarker[][] = script.segments.map(() => []);

    const sceneIsWebcam = sceneAssets.map((a) =>
      a.source === "webcam" || a.source === "broll-recorded"
    );

    // Which scenes have a recorded clip (webcam mode — video has embedded audio)
    const recordedSceneIndices = new Set<number>();
    for (const clip of webcamClips as any[]) {
      const i = Number(clip.segmentIndex);
      if (!Number.isFinite(i) || !script.segments[i]) continue;
      recordedSceneIndices.add(i);
    }
    // Also mark via studioScenes recordedUrl
    if (studioScenes) {
      for (let i = 0; i < studioScenes.length; i++) {
        if (studioScenes[i]?.recordedUrl) recordedSceneIndices.add(i);
      }
    }

    // Non-webcam scenes that need AI voice — generate individually
    const aiNeededIndices = script.segments
      .map((_, i) => i)
      .filter((i) => !recordedSceneIndices.has(i));

    console.log(`[render-video] Recorded scenes: [${[...recordedSceneIndices].join(",")}]`);
    console.log(`[render-video] AI voice needed: [${aiNeededIndices.join(",")}]`);

    // Generate one ElevenLabs clip per AI scene — simple, reliable, no slicing
    // When enableVoice=false we skip TTS entirely and render music-only.
    const perSceneAiVoice: (string | null)[] = new Array(script.segments.length).fill(null);
    let totalAiSeconds = 0;

    if (enableVoice) {
      console.log(`[render-video] Voice enabled — generating ${aiNeededIndices.length} ElevenLabs clips (voice: ${voiceId})`);
      for (const i of aiNeededIndices) {
        const narration = script.segments[i].narration?.trim();
        if (!narration) continue;
        try {
          const { audioBuffer, durationSec } = await generateVoiceover(narration, voiceId);
          if (!audioBuffer) { console.warn(`[render-video] Scene ${i+1}: no audio buffer`); continue; }
          const bytes = new Uint8Array(audioBuffer);
          const url   = await uploadFileToSpaces(
            new File([bytes], `voice-scene${i}-${Date.now()}.mp3`, { type: "audio/mpeg" })
          );
          perSceneAiVoice[i]                 = url;
          script.segments[i].durationSeconds = Math.max(durationSec, 3);
          totalAiSeconds                     += durationSec;
          console.log(`[render-video] Scene ${i+1}: AI voice ${durationSec.toFixed(1)}s → ${url}`);
        } catch (e) {
          console.error(`[render-video] Scene ${i+1}: voice gen failed`, e);
        }
      }
    } else {
      console.log("[render-video] Voice disabled — music-only mode. Scenes use preset durations.");
      // In music-only mode keep the scene durations from the script (editor estimates).
      // No TTS needed — music plays at full volume the whole time.
    }

    // brollAudioUrls = per-scene AI voice URLs (plain string, no JSON slice needed)
    for (const i of aiNeededIndices) {
      if (perSceneAiVoice[i]) brollAudioUrls[i] = perSceneAiVoice[i];
    }

    console.log(`[render-video] Audio summary: ${recordedSceneIndices.size} webcam (clip audio) + ${aiNeededIndices.length} AI scenes`);
    for (let i = 0; i < script.segments.length; i++) {
      const type = recordedSceneIndices.has(i) ? "WEBCAM-clip" : brollAudioUrls[i] ? "AI-voice" : "SILENT⚠";
      console.log(`  Scene ${i+1}: ${type}${brollAudioUrls[i] ? ` ${brollAudioUrls[i]!.slice(-30)}` : ""}`);
    }

    // ── Durations ─────────────────────────────────────────────────────────────
    // AI scenes: durationSeconds was set to real voice length above
    // Webcam scenes: use the recorded clip duration
    const sceneDurations = script.segments.map((seg, i) => {
      if (recordedSceneIndices.has(i)) {
        const d = webcamClipMap.get(i)?.duration ?? brollClipMap.get(i)?.duration;
        return asFiniteSeconds(d, asFiniteSeconds(seg?.durationSeconds, 6));
      }
      return asFiniteSeconds(seg?.durationSeconds, 4);
    });

    const totalDuration = sceneDurations.reduce((sum, d) => sum + d, 0);
    const totalFrames   = Math.max(1, Math.round(totalDuration * 30));
    console.log(`[render-video] Final: ${totalDuration.toFixed(1)}s → ${totalFrames} frames @30fps`);

    // ── 6) Music + DB template shapes ────────────────────────────────────────
    // Templates come from your DB (getTemplates), NOT from getPremiumComponent.
    //
    // Rules to avoid any overlapping text:
    //   1. Fetch templates from DB for the brand (if brandId supplied)
    //   2. Pick one template per scene by cycling through available templates
    //   3. Strip ALL text/label shapes from the template entirely
    //   4. Inject exactly ONE clean text shape per scene — screenText only,
    //      bottom-third position, semi-transparent pill, no animation conflicts
    //   5. All graphic/background/image shapes from the template pass through untouched
    //
    const musicMood = detectMusicMood(body_text || "", script.veo3StyleHint);

    // Fetch DB templates + music in parallel
    const brandId = body.brandId ?? body.brand_id ?? null;

    const [musicPath] = await Promise.all([
      downloadBackgroundMusic(musicMood).catch((e) => { console.warn("[music]", e); return null; }),
    ]);

        // ── sceneShapes: empty — CinematicTextOverlay inside MultiSceneVideo ────
    // Text rendering is fully handled by CinematicTextOverlay.tsx mounted
    // directly inside each Scene in MultiSceneVideo.tsx.
    // sceneShapes passed for backward-compat but intentionally ignored there.
    const sceneShapes: any[][] = script.segments.map(() => []);

    if (musicPath) tempFiles.push(musicPath);

    let musicUrl: string | null = null;

    if (musicPath) {
      try {
        musicUrl = await uploadFileToSpaces(
          new File([fs.readFileSync(musicPath)], `music-${Date.now()}.mp3`, { type: "audio/mpeg" })
        );
        console.log("[render-video] Music uploaded:", musicUrl);
      } catch (e) {
        console.warn("[music upload] failed:", e);
      }
    }

    // ── Fallback: local static file served by Next.js ───────────────────────
    // /public/fallback-music.mp3 is a 30s 432Hz corporate tone generated at build.
    // Remotion can fetch this directly from the Next.js dev/prod server.
    // No CDN, no external dependency, no 403 errors.
    if (!musicUrl) {
      // Resolve base URL: in production use NEXTAUTH_URL or APP_URL,
      // in dev fall back to localhost:3000
      const appBase = (
        process.env.NEXTAUTH_URL ||
        process.env.NEXT_PUBLIC_APP_URL ||
        process.env.APP_URL ||
        "http://localhost:3000"
      ).replace(/\/$/, "");
      musicUrl = `https://neuroflow.lon1.digitaloceanspaces.com/music/Alegend%20-%20Titanium%20(freetouse.com).mp3`;
      console.log(`[render-video] Using local fallback music: ${musicUrl}`);
    }

    // ── 8) Overlays ───────────────────────────────────────────────────────────
    const uploadedOverlaysByScene: MultiSceneVideoProps["uploadedOverlaysByScene"] = {};
    if (studioScenes) {
      for (let i = 0; i < studioScenes.length; i++) {
        const sb = studioScenes[i];
        if (!sb?.overlays?.length) continue;
        uploadedOverlaysByScene[i] = sb.overlays
          .filter((o) => !!o.url)
          .map((o) => ({
            id: o.id, type: o.type, url: o.url!,
            startSeconds: o.startSeconds, endSeconds: o.endSeconds,
            x: o.x, y: o.y, w: o.w, h: o.h, radius: o.radius,
          }));
      }
    }

    // ── 9) Remotion render ────────────────────────────────────────────────────
    const inputProps = {
      segments:           script.segments,
      sceneVideos:        sceneAssets.map((a) => a.videoUrl),
      sceneImages:        sceneAssets.map((a) => a.imageUrl),
      sceneShapes,
      sceneIsWebcam,
      sceneDurations,
      userRecordedVoice:  hasAnyUserVoice,
      campaignData:       campaignData as any,
      accentColor:        script.accentColor,
      companyName:        script.companyName,
      styleDNA:           script.styleDNA,
      musicUrl:           musicUrl  ?? undefined,
      musicVolume:        enableVoice ? 0.15 : 0.55,   // louder when no voice narration
      voiceUrl:           voiceUrl  ?? undefined,
      sceneAudioUrls,
      brollAudioUrls,
      sceneSpeechMarkers,
      captionsMode:       "off" as const,
      uploadedOverlaysByScene:
        Object.keys(uploadedOverlaysByScene).length > 0 ? uploadedOverlaysByScene : undefined,
      uploadedSceneMedia:
        uploadedSceneMediaFromBody.length > 0 ? uploadedSceneMediaFromBody : undefined,
    };

    const { renderMedia, selectComposition } = await import("@remotion/renderer");
    const bundleLocation = await getBundleLocation();

    const composition = await selectComposition({
      serveUrl:    bundleLocation,
      id:          "MultiSceneVideo",
      inputProps:  inputProps as any,
    });

    composition.durationInFrames = totalFrames;

    if (!Number.isFinite(composition.durationInFrames) || composition.durationInFrames <= 0) {
      throw new Error(`Invalid durationInFrames: ${composition.durationInFrames}`);
    }

    const outputPath = path.join(os.tmpdir(), `ad-${Date.now()}.mp4`);
    tempFiles.push(outputPath);

    console.log(`[render-video] Rendering ${totalFrames} frames...`);
    await renderMedia({
      composition,
      serveUrl:       bundleLocation,
      codec:          "h264",
      outputLocation: outputPath,
      inputProps:     inputProps as any,
    });

    const url = await uploadFileToSpaces(
      new File([fs.readFileSync(outputPath)], `ad-${Date.now()}.mp4`, { type: "video/mp4" })
    );

    console.log("[render-video] Done:", url);

    return NextResponse.json({
      ok: true,
      url,
      meta: {
        segments:      script.segments.length,
        totalSeconds:  totalDuration,
        sceneDurations,
        voiceMode:     !enableVoice ? "music-only" : hasAnyUserVoice ? "user-webcam+broll" : "ai-continuous",
        sources:       sceneAssets.map((a) => a.source),
        styleDNA:      script.styleDNA,
        markerCounts:  sceneSpeechMarkers.map((m) => m.length),
        captionsMode:  "off",
      },
    });

  } catch (err: any) {
    console.error("[render-video] Fatal:", err);
    return NextResponse.json({ ok: false, error: err?.message || "Render failed" }, { status: 500 });
  } finally {
    for (const f of tempFiles) {
      try { if (fs.existsSync(f)) fs.unlinkSync(f); } catch {}
    }
  }
}